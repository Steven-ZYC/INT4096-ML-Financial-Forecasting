"""Build every LaTeX asset from real run artifacts.

Nothing in the report's tables is typed by hand. This script reads
`experiments/models/*/*/metrics.json`, the snapshot manifests and the registry,
and emits `.tex` fragments plus vector figures into `deliverables/report/latex/`.

Regenerating the report therefore cannot silently disagree with the experiments:
if a table and the artifacts differ, one of them was not regenerated.

Usage:
    python scripts/build_latex_assets.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]

import sys

sys.path.insert(0, str(REPO_ROOT / "src"))

from int4096.config import load_protocol  # noqa: E402
from int4096.data.load import load_snapshot, read_manifest  # noqa: E402
from int4096.data.validate import validate_frame  # noqa: E402
from int4096.evaluation import figures  # noqa: E402
from int4096.experiments.run import prepare_dataset  # noqa: E402

LATEX_DIR = REPO_ROOT / "deliverables" / "report" / "latex"
GENERATED = LATEX_DIR / "generated"
FIGURES = LATEX_DIR / "figures"

MODEL_LABELS = {
    "naive_persistence": "Naive persistence",
    "linear_baseline": "Linear (OLS)",
    "ridge": "Ridge",
    "svr": "SVR (RBF)",
    "random_forest": "Random forest",
    "hist_gradient_boosting": r"Hist.\ gradient boosting",
}

MODEL_ORDER = [
    "linear_baseline",
    "ridge",
    "svr",
    "random_forest",
    "hist_gradient_boosting",
]


# --------------------------------------------------------------------- loading
def load_runs() -> pd.DataFrame:
    """One row per run, with metrics promoted to columns."""
    rows = []
    for path in sorted((REPO_ROOT / "experiments" / "models").glob("*/*/metrics.json")):
        blob = json.loads(path.read_text(encoding="utf-8"))
        metrics = blob.get("metrics", {})
        rows.append(
            {
                "run_id": blob["run_id"],
                "asset": blob["asset"],
                "model_id": blob["model_id"],
                "variant": blob["preprocess_variant"],
                "protocol": blob.get("protocol_version"),
                **{k.replace("validation_", ""): v for k, v in metrics.items()},
            }
        )
    if not rows:
        raise SystemExit("No metrics.json found. Run scripts/reproduce.sh first.")
    frame = pd.DataFrame(rows)
    # NaN arrives as the JSON literal NaN from the runner; keep it as NaN.
    return frame.replace({None: np.nan})


def tex_escape(text: str) -> str:
    return text.replace("_", r"\_")


def fmt(value, digits: int = 3, empty: str = "--") -> str:
    if value is None or (isinstance(value, float) and not np.isfinite(value)):
        return empty
    return f"{value:.{digits}f}"


def fmt_pct(value, digits: int = 2, empty: str = "--") -> str:
    if value is None or (isinstance(value, float) and not np.isfinite(value)):
        return empty
    return f"{value * 100:+.{digits}f}"


# ---------------------------------------------------------------- table: results
def write_results_table(runs: pd.DataFrame) -> Path:
    """Main comparison table: validation metrics per model and asset (P2)."""
    # ``groupby().last()`` keeps the builder deterministic even if a stale run
    # directory is left behind; the canonical cell is the most recent one.
    subset = (
        runs[runs["variant"] == "P2"]
        .sort_values("run_id")
        .groupby(["asset", "model_id"], as_index=True)
        .last()
    )
    lines = [
        "% GENERATED by scripts/build_latex_assets.py -- do not edit by hand.",
        "% Source: experiments/models/*/*/metrics.json (validation split only).",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Validation performance for each model family under the shared "
        r"protocol (variant P2, standardised inputs, seed 42). Skill is measured "
        r"against naive persistence on identical forecast dates. Absolute errors "
        r"are in quote currency and are \emph{not} comparable between AAPL and BTC; "
        r"only the unitless skill column is. The test block was not used.}",
        r"\label{tab:results}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}l r r r r r r@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{AAPL} & \multicolumn{3}{c}{BTC} \\",
        r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
        r"Model & MAE & RMSE & Skill & MAE & RMSE & Skill \\",
        r"\midrule",
    ]

    for model_id in MODEL_ORDER:
        cells = [MODEL_LABELS.get(model_id, tex_escape(model_id))]
        for asset in ("AAPL", "BTC"):
            try:
                row = subset.loc[(asset, model_id)]
            except KeyError:
                cells += ["--", "--", "--"]
                continue
            cells += [
                fmt(row["mae"], 2),
                fmt(row["rmse"], 2),
                r"\textbf{" + fmt_pct(row["skill_mae"]) + r"}" if row["skill_mae"] < 0
                else fmt_pct(row["skill_mae"]),
            ]
        lines.append(" & ".join(cells) + r" \\")

    # Baseline row, taken from any run's recorded baseline metrics.
    base = runs.dropna(subset=["baseline_mae"]).iloc[0]
    lines.append(r"\midrule")
    lines.append(
        "Naive persistence & "
        + fmt(base["baseline_mae"], 2)
        + " & "
        + fmt(base["baseline_rmse"], 2)
        + r" & 0.00 & "
        + fmt(runs[runs.asset == "BTC"].dropna(subset=["baseline_mae"]).iloc[0]["baseline_mae"], 2)
        + " & "
        + fmt(runs[runs.asset == "BTC"].dropna(subset=["baseline_rmse"]).iloc[0]["baseline_rmse"], 2)
        + r" & 0.00 \\"
    )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip\footnotesize",
        f"Skill is $1 - \\mathrm{{MAE}}_{{\\mathrm{{model}}}}/\\mathrm{{MAE}}_{{\\mathrm{{naive}}}}$ "
        f"in percent; negative values (bold) are worse than the baseline. "
        f"$n={int(base['n_obs'])}$ validation sessions per asset.",
        r"\end{table}",
        "",
    ]
    path = GENERATED / "results_table.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


# --------------------------------------------------------------- table: ablation
def write_ablation_table(runs: pd.DataFrame) -> Path:
    """P0 vs P2 contrast, matched by model and asset."""
    lines = [
        "% GENERATED by scripts/build_latex_assets.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Controlled preprocessing ablation: validation MAE without "
        r"standardisation (P0) and with it (P2), holding model, features, split and "
        r"tuning budget fixed. A change of exactly $0.000\%$ means the model is "
        r"invariant to monotone per-feature rescaling, which is the theoretical "
        r"prediction for tree ensembles and serves as a negative control.}",
        r"\label{tab:ablation}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}l r r r r r@{}}",
        r"\toprule",
        r" & \multicolumn{3}{c}{AAPL} & \multicolumn{2}{c}{BTC} \\",
        r"\cmidrule(lr){2-4}\cmidrule(l){5-6}",
        r"Model & P0 MAE & P2 MAE & $\Delta$ & P0 MAE & $\Delta$ \\",
        r"\midrule",
    ]
    for model_id in MODEL_ORDER:
        cells = [MODEL_LABELS.get(model_id, tex_escape(model_id))]
        for asset in ("AAPL", "BTC"):
            p0 = runs[(runs.asset == asset) & (runs.model_id == model_id) & (runs.variant == "P0")]
            p2 = runs[(runs.asset == asset) & (runs.model_id == model_id) & (runs.variant == "P2")]
            if p0.empty or p2.empty:
                cells += ["--", "--"] if asset == "BTC" else ["--", "--", "--"]
                continue
            a = float(p0.iloc[0]["mae"])
            b = float(p2.iloc[0]["mae"])
            delta = (b - a) / a * 100.0
            delta_tex = r"\textbf{0.000}" if abs(delta) < 5e-10 else f"{delta:+.3f}"
            if asset == "AAPL":
                cells += [fmt(a, 3), fmt(b, 3), delta_tex]
            else:
                cells += [fmt(a, 3), delta_tex]
        lines.append(" & ".join(cells) + r" \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip\footnotesize",
        r"$\Delta$ is the percentage change in validation MAE from P0 to P2. "
        r"Bold $0.000$ denotes bit-identical predictions.",
        r"\end{table}",
        "",
    ]
    path = GENERATED / "ablation_table.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


# ---------------------------------------------------------------- table: dataset
def write_dataset_table(protocol) -> Path:
    rows = []
    for asset in ("AAPL", "BTC"):
        frame = load_snapshot(asset)
        manifest = read_manifest(asset)
        report = validate_frame(frame, asset=asset)
        gaps = frame.index.to_series().diff().dt.days.dropna()
        rows.append(
            {
                "asset": asset,
                "provider": manifest["source"].get("provider"),
                "calendar": protocol.asset(asset)["calendar"].replace("_", " "),
                "bars": len(frame),
                "first": str(frame.index[0].date()),
                "last": str(frame.index[-1].date()),
                "max_gap": int(gaps.max()),
                "zero_vol": report.checks["zero_volume"],
                "sha": manifest["sha256"][:12],
            }
        )

    lines = [
        "% GENERATED by scripts/build_latex_assets.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Dataset provenance. Both series are committed as immutable "
        r"snapshots whose SHA-256 digest is verified before every experiment runs. "
        r"The two assets follow different calendars and are never aligned by row "
        r"index; BTC is a single-venue USDT price, not a global index.}",
        r"\label{tab:dataset}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3.5pt}",
        r"\begin{tabular}{@{}l l l r l l r r@{}}",
        r"\toprule",
        r"Asset & Provider & Calendar & Bars & First & Last & Max gap & SHA-256 \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['asset']} & {tex_escape(str(row['provider']))} & {row['calendar']} & "
            f"{row['bars']:,} & {row['first']} & {row['last']} & {row['max_gap']}d & "
            f"\\texttt{{{row['sha']}}} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip\footnotesize",
        r"Max gap is the largest interval between consecutive bars in calendar days: "
        r"weekend and holiday gaps are normal for an exchange calendar.",
        r"\end{table}",
        "",
    ]
    path = GENERATED / "dataset_table.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


# ----------------------------------------------------------------- table: splits
def write_split_table(protocol) -> Path:
    lines = [
        "% GENERATED by scripts/build_latex_assets.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Chronological split boundaries in the asset's own calendar. One "
        r"row is purged at each boundary so that no label crosses a split: with "
        r"$y_t = C_{t+1}$, the last training label would otherwise be a validation "
        r"price and the last validation label a sealed test price. The test block "
        r"remains unopened.}",
        r"\label{tab:splits}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}l l l l r@{}}",
        r"\toprule",
        r"Asset & Training & Validation & Sealed test & Total \\",
        r"\midrule",
    ]
    for asset in ("AAPL", "BTC"):
        prepared = prepare_dataset(asset, protocol)
        info = prepared["split"].describe(prepared["X"].index)
        total = len(prepared["X"])
        lines.append(
            f"{asset} & {info['train_period']} & {info['validation_period']} & "
            f"{info['test_period']} & {total:,} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\smallskip\footnotesize",
        r"Total is the number of usable feature rows after the trailing-window "
        r"warm-up and the terminal unlabelled row are removed.",
        r"\end{table}",
        "",
    ]
    path = GENERATED / "splits_table.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


# ------------------------------------------------------------------ macros file
def write_number_macros(runs: pd.DataFrame, protocol) -> Path:
    """Small macros so prose can cite measured values without retyping them."""
    p2 = (
        runs[runs["variant"] == "P2"]
        .sort_values("run_id")
        .groupby(["asset", "model_id"])
        .last()
    )

    def skill(asset: str, model: str) -> str:
        try:
            value = float(p2.loc[(asset, model)]["skill_mae"])
        except KeyError:
            return "--"
        return fmt_pct(value, 2)

    def mae(asset: str, model: str) -> str:
        try:
            return fmt(float(p2.loc[(asset, model)]["mae"]), 2)
        except KeyError:
            return "--"

    best_aapl_model = p2.loc["AAPL"]["skill_mae"].idxmax()
    best_btc_model = p2.loc["BTC"]["skill_mae"].idxmax()
    n_runs = len(runs)
    prepare = prepare_dataset("AAPL", protocol)

    macros = {
        "NRunTotal": str(n_runs),
        "NValAAPL": str(int(prepare["split"].validation_end - prepare["split"].validation_start)),
        "BestAAPLModel": tex_escape(MODEL_LABELS.get(best_aapl_model, best_aapl_model)),
        "BestBTCModel": tex_escape(MODEL_LABELS.get(best_btc_model, best_btc_model)),
        "BestAAPLSkill": skill("AAPL", best_aapl_model),
        "BestBTCSkill": skill("BTC", best_btc_model),
    }
    for asset in ("AAPL", "BTC"):
        for model in MODEL_ORDER:
            key = "".join(part.capitalize() for part in model.split("_"))
            macros[f"Skill{asset}{key}"] = skill(asset, model)
            macros[f"Mae{asset}{key}"] = mae(asset, model)

    lines = [
        "% GENERATED by scripts/build_latex_assets.py -- do not edit by hand.",
        "% Measured values referenced from prose, so no number is retyped by hand.",
    ]
    lines += [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros.items()]
    lines.append("")
    path = GENERATED / "numbers.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


# --------------------------------------------------------------------- figures
def write_figures(protocol) -> list[Path]:
    """Regenerate every report figure as PNG (for README) and PDF (for LaTeX)."""
    FIGURES.mkdir(parents=True, exist_ok=True)
    figures.EXTRA_FORMATS = (".pdf",)

    produced: list[Path] = []
    frames, splits = {}, {}
    for asset in ("AAPL", "BTC"):
        prepared = prepare_dataset(asset, protocol)
        frames[asset] = prepared["frame"]
        splits[asset] = prepared["split"]

    registry_path = REPO_ROOT / "experiments" / "models" / "registry.jsonl"
    registry = figures.load_registry()

    produced.append(
        figures.plot_coverage_and_splits(frames, splits, figure_root=FIGURES)
    )
    produced.append(
        figures.plot_asset_characteristics(frames, figure_root=FIGURES)
    )
    produced.append(figures.plot_model_vs_naive(registry, figure_root=FIGURES))
    produced.append(figures.plot_ablation_delta(registry, figure_root=FIGURES))

    # Sorted: iterdir() order is filesystem-dependent, which made this figure
    # (and its caption's run-id list) change between otherwise identical builds.
    run_dirs = sorted(
        (d for d in (REPO_ROOT / "experiments" / "models").glob("*/*") if d.is_dir()),
        key=lambda d: d.name,  # run ids start with a timestamp: chronological order
    )
    produced.append(figures.plot_train_vs_validation(run_dirs, figure_root=FIGURES))

    target = registry[
        (registry.status == "SUCCESS")
        & (registry.asset == "AAPL")
        & (registry.model_id == "svr")
        & (registry.preprocess_variant == "P2")
    ]
    if not target.empty:
        produced.append(
            figures.plot_observed_vs_predicted(
                target.iloc[0]["run_id"], figure_root=FIGURES
            )
        )
    return produced


def write_interpretability_figure(protocol) -> Path:
    """Permutation importance for a really-fitted model (no hand-typed values).

    A Ridge model is fitted on the training block exactly as the runner does, then
    each feature is shuffled on the validation block and the increase in MAE is
    recorded. This is a genuine measurement, regenerated from the same data and
    pipeline as the reported runs.
    """
    from sklearn.inspection import permutation_importance

    from int4096.evaluation.metrics import mae
    from int4096.models.base import build_estimator

    asset = "AAPL"
    prepared = prepare_dataset(asset, protocol)
    X, y, split = prepared["X"], prepared["y"], prepared["split"]
    frame = prepared["frame"]

    variant = protocol.variant("P2")
    train = np.arange(split.train_start, split.train_end)
    val = np.arange(split.validation_start, split.validation_end)

    model = build_estimator("ridge", {}, 42, variant)
    model.fit(X.iloc[train], y.iloc[train])

    reference = frame.loc[X.index[val], protocol.label_field].to_numpy()
    # Delta representation -> compare the reconstructed price forecast by MAE.
    truth = reference + y.iloc[val].to_numpy()

    def score(estimator, matrix, _y=None) -> float:
        # sklearn calls scorer(estimator, X, y); higher must be better.
        predicted = reference + estimator.predict(matrix)
        return -mae(truth, predicted)

    result = permutation_importance(
        model, X.iloc[val], y.iloc[val], scoring=score, n_repeats=20, random_state=42
    )
    importances = [
        {"feature": name, "importance": float(result.importances_mean[i])}
        for i, name in enumerate(X.columns)
    ]

    figures.EXTRA_FORMATS = (".pdf",)
    return figures.plot_feature_importance(
        importances,
        asset=asset,
        model_label="Ridge",
        n_obs=len(val),
        figure_root=FIGURES,
    )


def main() -> int:
    protocol = load_protocol()
    GENERATED.mkdir(parents=True, exist_ok=True)

    runs = load_runs()
    written = [
        write_results_table(runs),
        write_ablation_table(runs),
        write_dataset_table(protocol),
        write_split_table(protocol),
        write_number_macros(runs, protocol),
    ]
    written += write_figures(protocol)
    written.append(write_interpretability_figure(protocol))

    print(f"runs used: {len(runs)}")
    for path in written:
        print(f"  {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
