"""Render the bilingual speaker script to a printable PDF.

The Markdown in `docs/presentation/speaker_script_bilingual.md` is the source of
truth; this script converts it to LaTeX (xelatex + xeCJK, with a CJK font) and
compiles a PDF next to it. It handles exactly the constructs used in that file:
ATX headings, block quotes, pipe tables, bullet and checkbox lists, bold inline,
inline code, and rule lines.

Anything it does not recognise is emitted as a paragraph rather than dropped, so
text can never silently disappear from the printed script.

Usage:
    python scripts/build_script_pdf.py
Requires: xelatex, xeCJK, a CJK font (Fandol ships with TeX Live).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "docs" / "presentation" / "speaker_script_bilingual.md"
TEX = REPO_ROOT / "docs" / "presentation" / "speaker_script_bilingual.tex"
PDF = REPO_ROOT / "docs" / "presentation" / "speaker_script_bilingual.pdf"

PREAMBLE = r"""% GENERATED by scripts/build_script_pdf.py from speaker_script_bilingual.md
% Do not edit this .tex by hand: edit the Markdown and rebuild.
\documentclass[11pt,a4paper]{article}
\usepackage[margin=2.2cm]{geometry}
\usepackage{fontspec}
\usepackage{xeCJK}
% Explicit filenames: the Fandol family is not always registered by name.
\setCJKmainfont{FandolSong-Regular.otf}[BoldFont=FandolSong-Bold.otf]
\setCJKsansfont{FandolHei-Regular.otf}
\usepackage{amssymb}
\usepackage{booktabs}
\usepackage{longtable}
\usepackage{array}
\usepackage{xcolor}
\usepackage{enumitem}
\usepackage{titlesec}
\usepackage{fancyhdr}
\usepackage[hidelinks]{hyperref}
\usepackage{parskip}
\setcounter{secnumdepth}{0}

\definecolor{accent}{HTML}{1F4E79}
\definecolor{muted}{HTML}{555555}

\titleformat{\section}{\normalfont\Large\bfseries\color{accent}}{\thesection}{0.6em}{}
\titleformat{\subsection}{\normalfont\large\bfseries\color{accent}}{\thesubsection}{0.5em}{}
\titleformat{\subsubsection}{\normalfont\normalsize\bfseries}{}{0em}{}
\titlespacing*{\section}{0pt}{1.4em}{0.6em}
\titlespacing*{\subsection}{0pt}{1.1em}{0.4em}

\pagestyle{fancy}
\fancyhf{}
\fancyhead[L]{\footnotesize INT4096 --- Speaker script (English spoken, 中文对照)}
\fancyhead[R]{\footnotesize\thepage}
\renewcommand{\headrulewidth}{0.3pt}

\setlist[itemize]{leftmargin=1.2em,itemsep=1pt,topsep=2pt,parsep=0pt}
\newenvironment{scriptbox}{\begin{quote}\color{black}}{\end{quote}}
\newcommand{\zhnote}[1]{\par{\color{muted}#1\par}}

\begin{document}
"""

POSTAMBLE = "\n\\end{document}\n"


def esc(text: str) -> str:
    """Escape LaTeX specials, leaving UTF-8 (Chinese) untouched."""
    text = text.replace("\\", r"\textbackslash{}")
    for char, replacement in [
        ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
        ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
        ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
    ]:
        text = text.replace(char, replacement)
    return text


def inline(text: str) -> str:
    """Bold and inline code, after escaping."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", text)
    text = re.sub(r"`(.+?)`", r"\\texttt{\1}", text)
    return text


def level_guard(_out) -> bool:
    """Always true; keeps the quote-heading branch readable."""
    return True


def convert(markdown: str) -> str:
    out: list[str] = [PREAMBLE]
    lines = markdown.split("\n")
    i = 0
    in_quote = False
    in_list = False
    quote_buffer: list[str] = []

    def flush_quote() -> None:
        """Join consecutive quoted lines into ONE justified paragraph.

        Emitting a \\par per markdown line produced ragged, indented fragments
        in the printed script.
        """
        if quote_buffer:
            out.append(inline(esc(" ".join(quote_buffer))) + r"\par")
            quote_buffer.clear()

    def close_blocks() -> None:
        nonlocal in_quote, in_list
        flush_quote()
        if in_list:
            out.append(r"\end{itemize}")
            in_list = False
        if in_quote:
            out.append(r"\end{scriptbox}")
            in_quote = False

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # ---- table block -------------------------------------------------
        if stripped.startswith("|") and i + 1 < len(lines) and re.match(
            r"^\|[\s:\-|]+\|$", lines[i + 1].strip()
        ):
            close_blocks()
            header = [c.strip() for c in stripped.strip("|").split("|")]
            i += 2
            rows: list[list[str]] = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            width = len(header)
            # Explicit proportions per shape: a fixed 2-column layout broke every
            # table that had three or four columns.
            proportions = {
                1: [0.92],
                2: [0.28, 0.66],
                3: [0.20, 0.36, 0.36],
                4: [0.07, 0.24, 0.33, 0.28],
            }.get(width, [0.9 / width] * width)
            # Raw f-string: a non-raw one turns \textwidth into a TAB (\t).
            spec = "".join(rf"p{{{p:.2f}\textwidth}}" for p in proportions)
            out.append(r"{\footnotesize")
            out.append(r"\begin{longtable}{@{}" + spec + r"@{}}")
            out.append(r"\toprule")
            out.append(" & ".join(r"\textbf{" + inline(esc(h)) + "}" for h in header) + r" \\")
            out.append(r"\midrule")
            out.append(r"\endhead")
            for row in rows:
                row = (row + [""] * width)[:width]
                out.append(" & ".join(inline(esc(c)) for c in row) + r" \\")
            out.append(r"\bottomrule")
            out.append(r"\end{longtable}}")
            out.append("")
            continue

        # ---- headings ----------------------------------------------------
        heading = re.match(r"^(#{1,4})\s+(.*)$", stripped)
        if heading:
            close_blocks()
            level, text = len(heading.group(1)), heading.group(2)
            cmd = {1: "section", 2: "subsection", 3: "subsubsection", 4: "paragraph"}[level]
            # The level-1 title is the document title.
            if level == 1 and not out[-1].startswith("\\maketitle") and "\\maketitle" not in "".join(out):
                out.append(r"\begin{center}{\Large\bfseries\color{accent}" + inline(esc(text)) + r"}\end{center}")
                out.append(r"\vspace{2mm}\hrule\vspace{3mm}")
            else:
                out.append(f"\\{cmd}{{{inline(esc(text))}}}")
            out.append("")
            i += 1
            continue

        # ---- horizontal rule --------------------------------------------
        if re.match(r"^-{3,}$", stripped):
            close_blocks()
            out.append(r"\vspace{1mm}\hrule\vspace{2mm}")
            i += 1
            continue

        # ---- block quote (spoken English) -------------------------------
        if stripped.startswith(">"):
            text = stripped.lstrip(">").strip()
            if not in_quote:
                close_blocks()
                out.append(r"\begin{scriptbox}")
                in_quote = True
            heading_in_quote = re.match(r"^#{1,4}\s+(.*)$", text)
            if heading_in_quote and level_guard(out):
                quote_buffer.clear()
                out.append(r"{\bfseries " + inline(esc(heading_in_quote.group(1))) + r"}\par")
            elif text:
                quote_buffer.append(text)
            else:
                # A bare ">" ends the current quoted paragraph.
                flush_quote()
            i += 1
            continue

        # ---- bullets / checkboxes ---------------------------------------
        bullet = re.match(r"^[-*]\s+(?:\[([ xX])\]\s+)?(.*)$", stripped)
        if bullet:
            if in_quote:
                out.append(r"\end{scriptbox}")
                in_quote = False
            if not in_list:
                out.append(r"\begin{itemize}")
                in_list = True
            mark = ""
            if bullet.group(1) is not None:
                mark = r"$\square$ " if bullet.group(1).strip() == "" else r"$\boxtimes$ "
            out.append(r"  \item " + mark + inline(esc(bullet.group(2))))
            i += 1
            continue

        # ---- blank line --------------------------------------------------
        if not stripped:
            close_blocks()
            i += 1
            continue

        # ---- ordinary paragraph -----------------------------------------
        close_blocks()
        out.append(inline(esc(stripped)) + r"\par")
        i += 1

    close_blocks()
    out.append(POSTAMBLE)
    return "\n".join(out)


def main() -> int:
    if not SOURCE.exists():
        raise SystemExit(f"missing source: {SOURCE}")
    markdown = SOURCE.read_text(encoding="utf-8")
    TEX.write_text(convert(markdown), encoding="utf-8")

    result = subprocess.run(
        ["xelatex", "-interaction=nonstopmode", "-halt-on-error", TEX.name],
        cwd=TEX.parent,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stdout[-3000:])
        print("xelatex failed; see the log next to the .tex", file=sys.stderr)
        return 1

    # second pass for longtable column widths and page numbers
    subprocess.run(
        ["xelatex", "-interaction=nonstopmode", TEX.name],
        cwd=TEX.parent, capture_output=True, text=True,
    )

    for junk in TEX.parent.glob("speaker_script_bilingual.@(aux|log|out)"):
        junk.unlink(missing_ok=True)
    print(f"wrote {PDF.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
