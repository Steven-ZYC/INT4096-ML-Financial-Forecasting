"""Generate the slide deck's figures and number macros from run artifacts.

The deck shares its numbers with the report: both read `generated/numbers.tex`
produced here, so a slide cannot quote a value the experiments did not measure.
Vector figures are copied/regenerated as PDF for beamer.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from int4096.config import load_protocol  # noqa: E402
from int4096.evaluation import figures  # noqa: E402
from int4096.experiments.run import prepare_dataset  # noqa: E402

SLIDES = REPO_ROOT / "slides" / "latex"
GENERATED = SLIDES / "generated"
FIGURES = SLIDES / "figures"

# Figures used on slides, by base name in the shared figure directory.
WANTED = [
    "fig01_coverage_and_splits",
    "fig02_asset_characteristics",
    "fig04_model_vs_naive",
    "fig06_ablation_delta",
    "fig07_feature_importance_aapl",
]


def _model_macros(runs: dict) -> dict[str, str]:
    macros: dict[str, str] = {}

    def fmt(value, digits=2, pct=False):
        if value is None:
            return "--"
        return f"{value * 100:+.{digits}f}" if pct else f"{value:.{digits}f}"

    for (asset, model), row in runs.items():
        key = "".join(part.capitalize() for part in model.split("_"))
        macros[f"Skill{asset}{key}"] = fmt(row.get("skill_mae"), pct=True)
        macros[f"Mae{asset}{key}"] = fmt(row.get("mae"))

    best = {
        asset: max(
            ((m, r["skill_mae"]) for (a, m), r in runs.items() if a == asset),
            key=lambda pair: pair[1],
        )
        for asset in ("AAPL", "BTC")
    }
    macros["BestAAPLModel"] = {
        "svr": "SVR (RBF)",
        "ridge": "Ridge",
        "random_forest": "Random forest",
        "hist_gradient_boosting": "Hist.\\ gradient boosting",
        "linear_baseline": "Linear (OLS)",
    }[best["AAPL"][0]]
    macros["BestBTCModel"] = {
        "svr": "SVR (RBF)",
        "ridge": "Ridge",
        "random_forest": "Random forest",
        "hist_gradient_boosting": "Hist.\\ gradient boosting",
        "linear_baseline": "Linear (OLS)",
    }[best["BTC"][0]]
    macros["BestAAPLSkill"] = fmt(best["AAPL"][1], pct=True)
    macros["BestBTCSkill"] = fmt(best["BTC"][1], pct=True)
    # Count every executed cell, not just the P2 rows used in the table:
    # reporting "10 runs" from the filtered dict would understate the matrix.
    manifests = list((REPO_ROOT / "artifacts" / "experiments").glob("*/manifest.json"))
    macros["NRunTotal"] = str(len(manifests))
    return macros


def main() -> int:
    GENERATED.mkdir(parents=True, exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)

    rows: dict[tuple[str, str], dict] = {}
    for path in sorted((REPO_ROOT / "artifacts" / "experiments").glob("*/metrics.json")):
        blob = json.loads(path.read_text(encoding="utf-8"))
        if blob.get("preprocess_variant") != "P2":
            continue
        metrics = blob.get("metrics", {})
        rows[(blob["asset"], blob["model_id"])] = {
            "run_id": blob["run_id"],
            "mae": metrics.get("validation_mae"),
            "skill_mae": metrics.get("validation_skill_mae"),
        }
    if not rows:
        raise SystemExit("No P2 runs found; run scripts/reproduce.sh first.")

    macros = _model_macros(rows)
    lines = [
        "% GENERATED by scripts/build_slide_assets.py -- do not edit by hand.",
        "% Shared with the report: same artifacts, same macros, same numbers.",
    ]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    (GENERATED / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Prefer the vector PDFs already produced for the report.
    report_figs = REPO_ROOT / "reports" / "latex" / "figures"
    copied = 0
    for stem in WANTED:
        source = report_figs / f"{stem}.pdf"
        if not source.exists():
            figures.EXTRA_FORMATS = (".pdf",)
            protocol = load_protocol()
            frames, splits = {}, {}
            for asset in ("AAPL", "BTC"):
                prepared = prepare_dataset(asset, protocol)
                frames[asset] = prepared["frame"]
                splits[asset] = prepared["split"]
            figures.plot_coverage_and_splits(frames, splits, figure_root=report_figs)
            figures.plot_asset_characteristics(frames, figure_root=report_figs)
            registry = figures.load_registry()
            figures.plot_model_vs_naive(registry, figure_root=report_figs)
            figures.plot_ablation_delta(registry, figure_root=report_figs)
            target = registry[
                (registry.status == "SUCCESS")
                & (registry.asset == "AAPL")
                & (registry.model_id == "ridge")
                & (registry.preprocess_variant == "P2")
            ]
            if not target.empty:
                figures.plot_observed_vs_predicted(target.iloc[0]["run_id"], figure_root=report_figs)
            source = report_figs / f"{stem}.pdf"
        if source.exists():
            shutil.copy2(source, FIGURES / source.name)
            copied += 1
        else:
            print(f"  missing figure: {stem}.pdf")

    print(f"slide numbers: {len(macros)} macros, figures copied: {copied}/{len(WANTED)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
