"""Write the report's hyperparameter tuning table from the run records.

For each model: the search grid, how many distinct settings the random search
actually tried, and the setting chosen for each asset (P2 runs).

Usage (from the repository root):
    python scripts/build_report_tuning.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from int4096.config import load_protocol  # noqa: E402
from int4096.paths import REPORT_LATEX, run_files  # noqa: E402

OUTPUT = REPORT_LATEX / "generated" / "tuning_table.tex"
MODELS = {
    "linear_baseline": "Linear baseline",
    "ridge": "Ridge",
    "svr": "SVR (RBF)",
    "random_forest": "Random forest",
    "hist_gradient_boosting": r"Hist.\ gradient boosting",
}
NAMES = {"alpha": r"$\alpha$", "epsilon": r"$\varepsilon$", "gamma": r"$\gamma$", "C": "C",
         "learning_rate": "rate", "n_estimators": "trees", "max_depth": "depth",
         "min_samples_leaf": "leaf", "max_iter": "iterations"}


def text(value) -> str:
    if value is None:
        return "none"
    return f"{value:g}" if isinstance(value, (int, float)) else str(value)


def search_record(asset: str, model: str) -> dict:
    paths = run_files("metrics.json", f"*_{asset.lower()}_{model}_P2_*")
    if not paths:
        raise SystemExit(f"no P2 run for {asset} {model}")
    return json.loads(paths[-1].read_text(encoding="utf-8"))["search"]


def main() -> int:
    protocol = load_protocol()
    rows = []
    for model, label in MODELS.items():
        grid = protocol.model(model)["search_space"]
        size = math.prod(len(values) for values in grid.values())
        records = {asset: search_record(asset, model) for asset in ("AAPL", "BTC")}
        tried = {
            len({json.dumps(t["hyperparameters"], sort_keys=True) for t in r["trials"]})
            for r in records.values()
        }
        grid_text = "; ".join(
            f"{NAMES.get(k, k)} " + r"\{" + ", ".join(text(v) for v in values) + r"\}"
            for k, values in grid.items()
        )
        chosen = [
            ", ".join(f"{NAMES.get(k, k)} {text(v)}" for k, v in r["best_hyperparameters"].items())
            for r in records.values()
        ]
        coverage = "/".join(str(n) for n in sorted(tried)) + f" of {size}"
        rows.append(" & ".join([label, grid_text, coverage, *chosen]) + r" \\")

    lines = [
        "% GENERATED by scripts/build_report_tuning.py -- do not edit by hand.",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Search grids, distinct settings tried and chosen values "
        r"(standardised inputs, P2).}",
        r"\label{tab:tuning}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.15}",
        r"\begin{tabular}{@{}L{0.15\linewidth} L{0.34\linewidth} L{0.09\linewidth} "
        r"L{0.18\linewidth} L{0.18\linewidth}@{}}",
        r"\toprule",
        r"\textbf{Model} & \textbf{Search grid} & \textbf{Tried} & "
        r"\textbf{Chosen, AAPL} & \textbf{Chosen, BTC} \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
