"""Generate dataset cards and the feature dictionary from the real snapshots.

Outputs Markdown into ``docs/research/data_cards/`` and
``docs/research/feature_dictionary.md``. Every number in these documents is
computed from the snapshot, never typed by hand.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import pandas as pd

from ..config import REPO_ROOT, load_protocol
from ..data.load import load_snapshot, read_manifest
from ..data.validate import validate_frame
from ..features.build import build_features, feature_dictionary

DOCS_ROOT = REPO_ROOT / "docs" / "research"


def describe_frame(frame: pd.DataFrame) -> dict[str, Any]:
    """Descriptive statistics used in the dataset card."""
    returns = frame["close"].pct_change().dropna()
    gaps = frame.index.to_series().diff().dt.days.dropna()
    return {
        "rows": int(len(frame)),
        "first": str(frame.index[0].date()),
        "last": str(frame.index[-1].date()),
        "calendar_days": int((frame.index[-1] - frame.index[0]).days),
        "close_min": float(frame["close"].min()),
        "close_max": float(frame["close"].max()),
        "close_mean": float(frame["close"].mean()),
        "close_std": float(frame["close"].std()),
        "return_mean": float(returns.mean()),
        "return_std": float(returns.std()),
        "return_min": float(returns.min()),
        "return_max": float(returns.max()),
        "max_gap_days": int(gaps.max()) if len(gaps) else 0,
        "gaps_over_2d": int((gaps > 2).sum()),
        "zero_volume_rows": int((frame["volume"] == 0).sum()),
    }


def render_card(asset: str, frame: pd.DataFrame, manifest: dict[str, Any], stats: dict[str, Any],
                quality, feature_stats: dict[str, Any], protocol) -> str:
    cfg = protocol.asset(asset)
    adjustments = (
        f"Adjusted close differs from raw close on "
        f"{quality.checks.get('adj_close_differs_pct', 0):.1f}% of rows "
        f"({quality.checks.get('adj_close_differs_from_close', 0)} rows)."
        if quality.checks.get("has_adjusted_close")
        else "No corporate actions; adjusted close is not applicable."
    )

    lines = [
        f"# Dataset Card — {asset}",
        "",
        f"**Asset:** {asset}  ",
        f"**Quote currency:** {cfg.get('quote_currency')}  ",
        f"**Calendar:** {cfg.get('calendar')}  ",
        f"**Bar-close timezone:** {cfg.get('bar_close_timezone')}  ",
        f"**Protocol version:** `{protocol.version}`  ",
        "",
        "> This card is generated by `python -m int4096.data.cards` from the",
        "> immutable snapshot. Do not edit it by hand; regenerate it.",
        "",
        "## 1. Provenance",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Provider | `{manifest['source'].get('provider')}` |",
        f"| Endpoint | `{manifest['source'].get('endpoint') or manifest['source'].get('url')}` |",
        f"| Symbol | `{manifest['source'].get('symbol')}` |",
        f"| Snapshot file | `{manifest['snapshot_file']}` |",
        f"| SHA256 | `{manifest['sha256']}` |",
        f"| Bytes | {manifest['bytes']:,} |",
        f"| Downloaded (UTC) | `{manifest['downloaded_utc']}` |",
        f"| Rows | {manifest['row_count']:,} |",
        f"| First / last observation | {stats['first']} .. {stats['last']} |",
        "",
        "## 2. Coverage and calendar",
        "",
        f"- Observations: **{stats['rows']:,}** over {stats['calendar_days']:,} calendar days "
        f"(≈{stats['rows'] / max(stats['calendar_days'], 1) * 365:.0f} bars per year).",
        f"- Largest gap between consecutive observations: **{stats['max_gap_days']} days**.",
        f"- Gaps longer than 2 calendar days: **{stats['gaps_over_2d']}** "
        f"(weekends and exchange holidays for an equity calendar; these are *gaps, "
        f"not missing data*).",
        f"- Zero-volume rows: **{stats['zero_volume_rows']}**.",
        "",
        "## 3. Descriptive statistics (raw close)",
        "",
        "| Statistic | Value |",
        "|---|---|",
        f"| Min close | {stats['close_min']:,.2f} |",
        f"| Max close | {stats['close_max']:,.2f} |",
        f"| Mean close | {stats['close_mean']:,.2f} |",
        f"| Std. dev. close | {stats['close_std']:,.2f} |",
        f"| Mean daily return | {stats['return_mean'] * 100:.4f}% |",
        f"| Std. dev. daily return | {stats['return_std'] * 100:.4f}% |",
        f"| Min / max daily return | {stats['return_min'] * 100:.2f}% / {stats['return_max'] * 100:.2f}% |",
        "",
        "## 4. Data quality checks",
        "",
        f"Overall: **{'PASS' if quality.passed else 'ISSUES'}**",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Non-positive prices | {sum(quality.checks.get('non_positive_prices', {}).values())} |",
        f"| Rows with high < low | {quality.checks.get('high_below_low')} |",
        f"| Rows with close outside [low, high] | {quality.checks.get('close_outside_high_low')} |",
        f"| Negative volume rows | {quality.checks.get('negative_volume')} |",
        f"| Duplicate timestamps | 0 (loader rejects them) |",
        f"| Missing core values | {sum(v for k, v in quality.checks.get('missing_values', {}).items() if k != 'adj_close')} |",
        "",
        "## 5. Corporate actions",
        "",
        adjustments,
        "",
        "**Consequence for the target.** The label uses the **raw close**. Adjusted",
        "close embeds dividend and split factors that the provider revises after the",
        "fact, so a model trained on today's adjusted history would see numbers that",
        "did not exist at the original decision time. That is a subtle leakage",
        "channel. The 2021-10-28.. window was checked for splits: no adjustment jump",
        "larger than 2% occurs, so the raw series is free of split discontinuities",
        "within this window. See protocol decision D1/D4.",
        "",
        "## 6. Features derived from this snapshot",
        "",
        "| Aspect | Value |",
        "|---|---|",
        f"| Design-matrix rows after warm-up | {feature_stats['n_rows']} |",
        f"| Rows dropped for warm-up (`lookback={protocol.lookback}`) | {feature_stats['dropped_warmup']} |",
        f"| Terminal row dropped (no observable t+1) | 1 |",
        f"| Feature columns | {feature_stats['n_features']} |",
        f"| Missing values in design matrix | {feature_stats['n_missing']} |",
        "",
        "## 7. Known limitations",
        "",
        f"- {'USDT is not exactly USD and Binance is a single venue; this is a venue-specific price, not a global index.' if asset == 'BTC' else 'A single exchange listing; after-hours and pre-market prices are excluded by the daily bar definition.'}",
        "- Daily bars collapse intra-day information; the label is a session-to-session close.",
        "- Provider revisions are not tracked beyond the snapshot checksum; a re-download may differ.",
        "",
        "## 8. Reproduction",
        "",
        "```bash",
        f"python -m int4096.data.snapshot --asset {asset}   # writes immutable snapshot + manifest",
        f"python -m int4096.data.cards                      # regenerates this card",
        "```",
        "",
    ]
    if quality.issues:
        lines += ["## 9. Outstanding issues", ""]
        lines += [f"- {issue}" for issue in quality.issues]
        lines += [""]
    return "\n".join(lines)


def write_cards(protocol_path: str | None = None, out_dir: str | Path | None = None) -> list[Path]:
    protocol = load_protocol(protocol_path)
    out = Path(out_dir) if out_dir else DOCS_ROOT / "data_cards"
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    for asset in ("AAPL", "BTC"):
        frame = load_snapshot(asset, protocol_path=protocol_path)
        manifest = read_manifest(asset, protocol_path=protocol_path)
        quality = validate_frame(frame, asset=asset)
        stats = describe_frame(frame)

        X, y = build_features(
            frame,
            label_field=protocol.label_field,
            lookback=protocol.lookback,
            min_periods=protocol.min_periods,
            mode=protocol.label_mode,
        )
        feature_stats = {
            "n_rows": len(X),
            "n_features": X.shape[1],
            "n_missing": int(X.isna().sum().sum()),
            "dropped_warmup": int(len(frame) - len(X) - 1),
        }

        card = render_card(asset, frame, manifest, stats, quality, feature_stats, protocol)
        path = out / f"{asset.lower()}_dataset_card.md"
        path.write_text(card, encoding="utf-8")
        written.append(path)

    # Feature dictionary (single, shared across assets).
    lines = [
        "# Feature Dictionary",
        "",
        "Generated by `python -m int4096.data.cards` from `int4096.features.build`.",
        "",
        "Every feature is computable from bars `<= t`. The prediction is made",
        "immediately after bar `t` closes.",
        "",
        "| Feature | Definition | Trailing window |",
        "|---|---|---|",
    ]
    for row in feature_dictionary():
        lines.append(
            f"| `{row['feature']}` | {row['definition']} | {row['window']} |"
        )
    lines += [
        "",
        "## Explicit prohibitions",
        "",
        "- No centred rolling window (`center=True`).",
        "- No negative shift inside the design matrix.",
        "- No `bfill` / backward fill.",
        "- No whole-dataset statistic in feature construction or preprocessing.",
        "- No price-level feature, so the label must be modelled as a change "
        "(see protocol decision D8).",
        "",
        "These are enforced by `tests/test_temporal_integrity.py`.",
        "",
    ]
    dict_path = DOCS_ROOT / "feature_dictionary.md"
    dict_path.write_text("\n".join(lines), encoding="utf-8")
    written.append(dict_path)
    return written


def _main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate dataset cards.")
    parser.add_argument("--protocol", default=None)
    parser.add_argument("--out-dir", default=None)
    args = parser.parse_args(argv)
    for path in write_cards(args.protocol, args.out_dir):
        print(path)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(_main())
